-- Arithmetic Operators
-- Arithmetic operators are used to perform mathematical calculations.

-- Addition
-- +

SELECT 10 + 2;

-- Subtraction

---

SELECT 10 - 2;

-- Multiplication
-- *

SELECT 5 * 3;

-- Division
-- /

SELECT 10 / 2;

-- Exponentiation
-- ^

SELECT 10 ^ 2;

-- Modulo
-- %
-- Returns the remainder after division.

SELECT 10 % 3;

-- More examples

SELECT 20 + 5;

SELECT 20 - 5;

SELECT 20 * 5;

SELECT 20 / 5;

SELECT 2 ^ 3;

SELECT 10 % 3;

-- Notes
-- +  = Addition
-- -  = Subtraction
-- *  = Multiplication
-- /  = Division
-- ^  = Exponentiation
-- %  = Modulo (remainder)
